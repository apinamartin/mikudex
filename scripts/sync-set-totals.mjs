// One-off development utility.
//
// TCGdex only exposes partial card counters on /series/:id, so the app cannot know how many
// reverse holo variants a set holds without asking for every single card. This script walks the
// whole English catalog once and writes the exact numbers into src/adapters/tcgdex/setTotals.ts,
// which ships with the build so the home page renders final counts immediately.
//
//   npm run sync:totals            # refresh every set
//   npm run sync:totals -- --force # ignore the cached partial results and start from scratch
//
// The run is resumable: progress is stored in scripts/.set-totals.partial.json.

import { readFile, writeFile, rename } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const API = 'https://api.tcgdex.net/v2/en'
const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const OUTPUT = join(ROOT, 'src', 'adapters', 'tcgdex', 'generatedSetTotals.ts')
const PARTIAL = join(ROOT, 'scripts', '.set-totals.partial.json')
const CARD_CONCURRENCY = 12
const FORCE = process.argv.includes('--force')

async function getJSON(path, attempts = 6) {
  let lastError
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    try {
      const response = await fetch(`${API}${path}`)
      if (response.status === 429) {
        const wait = 1000 * 2 ** attempt
        console.warn(`  rate limited on ${path}, waiting ${wait}ms`)
        await new Promise(resolve => setTimeout(resolve, wait))
        continue
      }
      if (!response.ok) throw new Error(`HTTP ${response.status}`)
      return await response.json()
    } catch (cause) {
      lastError = cause
      await new Promise(resolve => setTimeout(resolve, 500 * (attempt + 1)))
    }
  }
  throw new Error(`${path}: ${lastError instanceof Error ? lastError.message : String(lastError)}`)
}

async function countReverseHolos(setId, cards) {
  const queue = [...cards]
  let reverse = 0
  let failed = 0

  async function worker() {
    while (queue.length) {
      const card = queue.shift()
      try {
        const details = await getJSON(`/cards/${encodeURIComponent(card.id)}`, 4)
        if (details?.variants?.reverse) reverse += 1
      } catch {
        failed += 1
      }
    }
  }

  await Promise.all(Array.from({ length: Math.min(CARD_CONCURRENCY, cards.length) }, worker))
  return { reverse, failed }
}

let writeQueue = Promise.resolve()
function savePartial(totals) {
  writeQueue = writeQueue.then(() => writeFile(PARTIAL, JSON.stringify(totals, null, 2)))
}

async function main() {
  let totals = {}
  if (!FORCE) {
    try {
      totals = JSON.parse(await readFile(PARTIAL, 'utf8'))
    } catch {
      totals = {}
    }
  }

  const series = await getJSON('/series')
  const sets = []
  for (const entry of series) {
    const detail = await getJSON(`/series/${entry.id}`)
    for (const set of detail.sets ?? []) sets.push({ ...set, series: entry.id })
  }
  console.log(`${series.length} series · ${sets.length} sets · ${Object.keys(totals).length} already resolved`)

  let done = 0
  for (const set of sets) {
    if (totals[set.id]) {
      done += 1
      continue
    }

    let metadata
    try {
      metadata = await getJSON(`/sets/${set.id}`)
    } catch (cause) {
      console.warn(`skip ${set.id}: ${cause.message}`)
      continue
    }

    const cards = metadata.cards ?? []
    const { reverse, failed } = await countReverseHolos(set.id, cards)
    if (failed) {
      console.warn(`incomplete ${set.id} (${failed} card requests failed) — will retry on next run`)
      continue
    }

    totals[set.id] = { total: cards.length, reverse }
    done += 1
    console.log(`[${done}/${sets.length}] ${set.id.padEnd(8)} total ${String(cards.length).padStart(4)} + reverse ${String(reverse).padStart(4)}`)
    savePartial(totals)
  }

  await writeQueue
  await writeFile(PARTIAL, JSON.stringify(totals, null, 2))

  const sorted = Object.fromEntries(Object.entries(totals).sort(([a], [b]) => a.localeCompare(b)))
  const body = Object.entries(sorted)
    .map(([id, entry]) => `  ${JSON.stringify(id)}: { total: ${entry.total}, reverse: ${entry.reverse} },`)
    .join('\n')

  const source = `// Generated by scripts/sync-set-totals.mjs — do not edit by hand.
// Exact card counters per set, straight from TCGdex card variants: "total" is the number of
// cards listed in the set, "reverse" the number of those cards that have a reverse holo print.

export type SetTotals = { total: number; reverse: number }

export const generatedSetTotals: Record<string, SetTotals> = {
${body}
}
`

  const temporary = `${OUTPUT}.tmp`
  await writeFile(temporary, source)
  await rename(temporary, OUTPUT)
  console.log(`wrote ${Object.keys(sorted).length} sets to ${OUTPUT}`)
}

main().catch(cause => {
  console.error(cause)
  process.exitCode = 1
})
